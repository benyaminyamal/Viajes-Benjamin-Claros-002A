export function listDestinations({ region, q } = {}) {
  let result = destinations.map(toPublicDestination);

  if (region) {
    const wanted = normalize(region);
    result = result.filter((destination) => normalize(destination.region) === wanted);
  }

  if (q) {
    const needle = normalize(q);
    result = result.filter((destination) =>
      normalize(
        [
          destination.name,
          destination.country,
          destination.region,
          destination.tagline,
          destination.description,
          ...destination.popularActivities,
        ].join(' '),
      ).includes(needle),
    );
  }

  return result;
}

export function findDestination(id) {
  const destination = destinations.find((item) => item.id === id);
  return destination ? toPublicDestination(destination) : null;
}

export function listRegions() {
  return [...new Set(destinations.map((destination) => destination.region))];
}

export function listFlights(destinationId) {
  return flights
    .filter((item) => item.destinationId === destinationId)
    .map((item) => withAvailability(item, 'availableSeats'));
}

export function findFlight(id) {
  const item = flights.find((flightItem) => flightItem.id === id);
  return item ? withAvailability(item, 'availableSeats') : null;
}

export function listHotels(destinationId) {
  return hotels
    .filter((item) => item.destinationId === destinationId)
    .map((item) => withAvailability(item, 'availableRooms'));
}

export function findHotel(id) {
  const item = hotels.find((hotelItem) => hotelItem.id === id);
  return item ? withAvailability(item, 'availableRooms') : null;
}

function toPublicDestination(destination) {
  const { departureDate, returnDate, ...publicDestination } = destination;
  return publicDestination;
}

function withAvailability(item, seatsKey) {
  return {
    ...item,
    available: Boolean(item.available) && item[seatsKey] > 0,
  };
}

function normalize(value) {
  return String(value)
    .toLocaleLowerCase('es')
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '');
}
