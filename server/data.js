const byId = Object.fromEntries(destinations.map((destination) => [destination.id, destination]));

function flight(destinationId, fields) {
  const destination = byId[destinationId];
  return {
    currency: 'USD',
    cabin: 'Económica',
    available: true,
    stops: 0,
    originCity: 'Santiago',
    originCode: 'SCL',
    destinationId,
    destinationCity: destination.name,
    destinationCode: destination.airport,
    departureDate: destination.departureDate,
    returnDate: destination.returnDate,
    ...fields,
  };
}

function hotel(destinationId, fields) {
  const destination = byId[destinationId];
  return {
    currency: 'USD',
    available: true,
    destinationId,
    checkIn: destination.departureDate,
    checkOut: destination.returnDate,
    ...fields,
  };
}

